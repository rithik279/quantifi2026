"""Paste src/trader.py and its strategies into one uploadable file.

Usage (from the repo root):
    python src/build_submission.py            # writes submission/trader.py
    python src/backtester.py submission/trader.py

Checks along the way:
- imports are standard library or `datamodel` only (numpy/pandas are not
  confirmed for the official backtester; pass --allow-numpy once they are);
- no two files define the same module-level name, since they share one file.
"""

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
OUT = ROOT / "submission" / "trader.py"


def module_files() -> list:
    """common.py first, then strategies in the order trader.py imports them, then trader.py."""
    tree = ast.parse((SRC / "trader.py").read_text())
    mods = [n.module for n in tree.body if isinstance(n, ast.ImportFrom)
            and n.module and n.module.startswith("strategies.")]
    files = [SRC / "strategies" / "common.py"]
    files += [SRC / (m.replace(".", "/") + ".py") for m in mods if m != "strategies.common"]
    return files + [SRC / "trader.py"]


def defined_names(tree: ast.Module) -> set:
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef, ast.AsyncFunctionDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names |= {t.id for t in node.targets if isinstance(t, ast.Name)}
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return names


def build(allow_numpy: bool) -> str:
    allowed = set(sys.stdlib_module_names) | {"datamodel"}
    if allow_numpy:
        allowed |= {"numpy", "pandas"}

    errors, owner = [], {}
    datamodel_names, header_imports, bodies = set(), [], []
    for path in module_files():
        rel = path.relative_to(ROOT)
        source = path.read_text()
        tree = ast.parse(source, filename=str(rel))
        lines = source.splitlines()
        drop = set()

        for node in tree.body:
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                if isinstance(node, ast.ImportFrom):
                    top = (node.module or "").split(".")[0]
                    if node.module == "__future__":
                        errors.append(f"{rel}: drop `from __future__` imports")
                else:
                    top = node.names[0].name.split(".")[0]
                if top == "strategies":
                    pass
                elif top == "datamodel":
                    datamodel_names |= {a.name for a in node.names}
                elif top not in allowed:
                    errors.append(f"{rel}:{node.lineno}: `{top}` may not exist on the official backtester")
                else:
                    header_imports.append(ast.get_source_segment(source, node))
                drop |= set(range(node.lineno, node.end_lineno + 1))
            elif (isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant)
                  and isinstance(node.value.value, str) and node is tree.body[0]):
                drop |= set(range(node.lineno, node.end_lineno + 1))  # module docstring

        for name in defined_names(tree):
            if name in owner:
                errors.append(f"{rel}: `{name}` is also defined in {owner[name]}; rename one")
            owner[name] = rel

        body = "\n".join(l for i, l in enumerate(lines, 1) if i not in drop).strip("\n")
        bodies.append(f"# {'=' * 70}\n# {rel}\n# {'=' * 70}\n\n{body}\n")

    if errors:
        raise SystemExit("build failed:\n  " + "\n  ".join(errors))

    imports = list(dict.fromkeys(header_imports))
    head = [
        '"""UTEFA QuantiFi 2026, Team #21. Generated by src/build_submission.py; edit the sources, not this file."""',
        "",
        *imports,
        "",
        f"from datamodel import {', '.join(sorted(datamodel_names))}",
        "",
    ]
    return "\n".join(head) + "\n\n" + "\n\n".join(bodies)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--allow-numpy", action="store_true")
    args = ap.parse_args()

    code = build(args.allow_numpy)
    compile(code, str(OUT), "exec")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(code)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(code.splitlines())} lines)")


if __name__ == "__main__":
    main()
